  minutes INTEGER,
  points INTEGER,
  o_rebounds INTEGER,
  d_rebounds INTEGER,
  rebounds INTEGER,
  assists INTEGER,
  steals INTEGER,
  blocks INTEGER,
  turnovers INTEGER,
  personal_fouls INTEGER,
  fg_attempted INTEGER,
  fg_made INTEGER,
  ft_attempted INTEGER,
  ft_made INTEGER,
  three_attempted INTEGER,
  three_made INTEGER,
  FOREIGN KEY (playerID) REFERENCES players(playerID)
);

CREATE TABLE players (
  playerID TEXT,
  useFirst TEXT,
  firstName TEXT,
  middleName TEXT,
  lastName TEXT,
  nameGiven TEXT,
  fullGivenName TEXT,
  nameSuffix TEXT,
  nameNick TEXT,
  pos TEXT,
  firstseason INTEGER,
  lastseason INTEGER,
  height REAL,
  weight INTEGER,
  college TEXT,
  collegeOther TEXT,
  birthDate TEXT,
  birthCity TEXT,
  birthState TEXT,
  birthCountry TEXT,
  highSchool TEXT,
  hsCity TEXT,
  hsState TEXT,
  hsCountry TEXT,
  deathDate TEXT,
  race TEXT,
  PRIMARY KEY (playerID)
);

CREATE TABLE teams (
  year INTEGER,
  lgID TEXT,
  tmID TEXT,
  franchID TEXT,
  confID TEXT,
  divID TEXT,
  rank INTEGER,
  confRank INTEGER,
  playoff TEXT,
  name TEXT,
  o_fgm INTEGER,
  o_ftm INTEGER,
  o_pts INTEGER,
  d_pts INTEGER,
  homeWon INTEGER,
  homeLost INTEGER,
  awayWon INTEGER,
  awayLost INTEGER,
  won INTEGER,
  lost INTEGER,
  games INTEGER,
  arena TEXT
);

CREATE TABLE awards_coaches (
  id INTEGER,
  year INTEGER,
  coachID TEXT,
  award TEXT,
  lgID TEXT,
  note TEXT,
  PRIMARY KEY (id),
  FOREIGN KEY (year) REFERENCES coaches(year),
  FOREIGN KEY (coachID) REFERENCES coaches(coachID)
);

