CREATE TABLE series_post (
  id INTEGER,
  year INTEGER,
  round TEXT,
  series TEXT,
  tmIDWinner TEXT,
  lgIDWinner TEXT,
  tmIDLoser TEXT,
  lgIDLoser TEXT,
  W INTEGER,
  L INTEGER,
  PRIMARY KEY (id),
  FOREIGN KEY (year) REFERENCES teams(year),
  FOREIGN KEY (tmIDWinner) REFERENCES teams(tmID),
  FOREIGN KEY (tmIDLoser) REFERENCES teams(tmID)
