CREATE TABLE awards_players (
  playerID TEXT,
  award TEXT,
  year INTEGER,
  lgID TEXT,
  note TEXT,
  pos TEXT,
  FOREIGN KEY (playerID) REFERENCES players(playerID)
);

CREATE TABLE coaches (
  coachID TEXT,
  year INTEGER,
  tmID TEXT,
  lgID TEXT,
  stint INTEGER,
  won INTEGER,
  lost INTEGER,
  post_wins INTEGER,
  post_losses INTEGER,
  FOREIGN KEY (year) REFERENCES teams(year),
  FOREIGN KEY (tmID) REFERENCES teams(tmID)
);

CREATE TABLE draft (
  id INTEGER,
  draftYear INTEGER,
  draftRound INTEGER,
  draftSelection INTEGER,
  draftOverall INTEGER,
  tmID TEXT,
  firstName TEXT,
  lastName TEXT,
  suffixName TEXT,
  playerID TEXT,
  draftFrom TEXT,
  lgID TEXT,
  PRIMARY KEY (id),
  FOREIGN KEY (draftYear) REFERENCES teams(year),
  FOREIGN KEY (tmID) REFERENCES teams(tmID)
);

